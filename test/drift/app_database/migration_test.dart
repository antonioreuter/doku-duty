// ignore_for_file: unused_local_variable, unused_import
import 'package:drift/drift.dart';
import 'package:drift_dev/api/migrations_native.dart';
import 'package:doku_duty/features/persistence/data/app_database.dart';
import 'package:flutter_test/flutter_test.dart';
import 'generated/schema.dart';

import 'generated/schema_v1.dart' as v1;
import 'generated/schema_v2.dart' as v2;
import 'generated/schema_v3.dart' as v3;

void main() {
  driftRuntimeOptions.dontWarnAboutMultipleDatabases = true;
  late SchemaVerifier verifier;

  setUpAll(() {
    verifier = SchemaVerifier(GeneratedHelper());
  });

  group('simple database migrations', () {
    // These simple tests verify all possible schema updates with a simple (no
    // data) migration. This is a quick way to ensure that written database
    // migrations properly alter the schema.
    const versions = GeneratedHelper.versions;
    for (final (i, fromVersion) in versions.indexed) {
      group('from $fromVersion', () {
        for (final toVersion in versions.skip(i + 1)) {
          test('to $toVersion', () async {
            final schema = await verifier.schemaAt(fromVersion);
            final db = AppDatabase(schema.newConnection());
            await verifier.migrateAndValidate(db, toVersion);
            await db.close();
          });
        }
      });
    }
  });

  // Adopted from the generated template, as its own TODO asks.
  //
  // The tests above prove the schema arrives at the right shape. This one puts
  // a real session into a version 1 database and checks it is still there
  // afterwards — which is the thing D-33 exists to protect, and the thing a
  // schema check cannot see. Version 2 only adds a table, so every row below
  // must come through byte for byte.
  //
  // These classes sit between the mapped API and sqlite: timestamps are
  // DateTime, but booleans are still the integers sqlite stores.
  test('migration from v1 to v2 does not corrupt data', () async {
    // The two snapshots were generated by different drift_dev versions — v1
    // before the toolchain pin in D-77, v2 after it — so v1's helper classes
    // expose sqlite's storage types (String, int) while v2's expose the mapped
    // ones (DateTime, bool). Same database either side; different generated
    // surface. Each list is written to its own version's shape.
    final stampText = DateTime.utc(2026, 9, 6, 12).toIso8601String();
    final stamp = DateTime.utc(2026, 9, 6, 12);

    // A part-solved puzzle with one settled note and one provisional note.
    final oldNotesData = <v1.NotesData>[
      v1.NotesData(
        puzzleId: 'p1',
        cell: 40,
        digit: 7,
        kind: 'settled',
        origin: 'generated',
        updatedAt: stampText,
        pendingUpload: 1,
      ),
      v1.NotesData(
        puzzleId: 'p1',
        cell: 41,
        digit: 2,
        kind: 'provisional',
        origin: 'manual',
        updatedAt: stampText,
        pendingUpload: 1,
      ),
    ];
    final expectedNewNotesData = <v2.NotesData>[
      v2.NotesData(
        puzzleId: 'p1',
        cell: 40,
        digit: 7,
        kind: 'settled',
        origin: 'generated',
        updatedAt: stamp,
        pendingUpload: true,
      ),
      v2.NotesData(
        puzzleId: 'p1',
        cell: 41,
        digit: 2,
        kind: 'provisional',
        origin: 'manual',
        updatedAt: stamp,
        pendingUpload: true,
      ),
    ];

    const grid =
        '53..7....6..195....98....6.8...6...34..8.3..17...2...6.6....28....419..5....8..79';
    final oldPuzzleSavesData = <v1.PuzzleSavesData>[
      v1.PuzzleSavesData(
        puzzleId: 'p1',
        placedValues: grid,
        elapsedMs: 742000,
        isComplete: 0,
        updatedAt: stampText,
        pendingUpload: 1,
        deviceOrigin: 'test-device',
      ),
    ];
    final expectedNewPuzzleSavesData = <v2.PuzzleSavesData>[
      v2.PuzzleSavesData(
        puzzleId: 'p1',
        placedValues: grid,
        elapsedMs: 742000,
        isComplete: false,
        updatedAt: stamp,
        pendingUpload: true,
        deviceOrigin: 'test-device',
      ),
    ];

    final oldPacksData = <v1.PacksData>[];
    final expectedNewPacksData = <v2.PacksData>[];

    final oldPuzzlesData = <v1.PuzzlesData>[];
    final expectedNewPuzzlesData = <v2.PuzzlesData>[];

    final oldSolvedPuzzlesData = <v1.SolvedPuzzlesData>[];
    final expectedNewSolvedPuzzlesData = <v2.SolvedPuzzlesData>[];

    final oldLifetimeStatsData = <v1.LifetimeStatsData>[
      v1.LifetimeStatsData(
        id: 0,
        puzzlesSolved: 41,
        perfectSolves: 12,
        totalPlayMs: 9000000,
        updatedAt: stampText,
        pendingUpload: 1,
      ),
    ];
    final expectedNewLifetimeStatsData = <v2.LifetimeStatsData>[
      v2.LifetimeStatsData(
        id: 0,
        puzzlesSolved: 41,
        perfectSolves: 12,
        totalPlayMs: 9000000,
        updatedAt: stamp,
        pendingUpload: true,
      ),
    ];

    final oldTechniqueStatsData = <v1.TechniqueStatsData>[
      v1.TechniqueStatsData(
        technique: 'xWing',
        puzzlesRequiring: 9,
        updatedAt: stampText,
        pendingUpload: 1,
      ),
    ];
    final expectedNewTechniqueStatsData = <v2.TechniqueStatsData>[
      v2.TechniqueStatsData(
        technique: 'xWing',
        puzzlesRequiring: 9,
        updatedAt: stamp,
        pendingUpload: true,
      ),
    ];

    // reduceEffects turned on. Its default is off, so a setting that reverted
    // would be silently wrong rather than obviously missing.
    final oldSettingsData = <v1.SettingsData>[
      v1.SettingsData(
        key: 'reduceEffects',
        boolValue: 1,
        updatedAt: stampText,
        pendingUpload: 1,
      ),
    ];
    final expectedNewSettingsData = <v2.SettingsData>[
      v2.SettingsData(
        key: 'reduceEffects',
        boolValue: true,
        updatedAt: stamp,
        pendingUpload: true,
      ),
    ];

    await verifier.testWithDataIntegrity(
      oldVersion: 1,
      newVersion: 2,
      createOld: v1.DatabaseAtV1.new,
      createNew: v2.DatabaseAtV2.new,
      openTestedDatabase: AppDatabase.new,
      createItems: (batch, oldDb) {
        batch.insertAll(oldDb.notes, oldNotesData);
        batch.insertAll(oldDb.puzzleSaves, oldPuzzleSavesData);
        batch.insertAll(oldDb.packs, oldPacksData);
        batch.insertAll(oldDb.puzzles, oldPuzzlesData);
        batch.insertAll(oldDb.solvedPuzzles, oldSolvedPuzzlesData);
        batch.insertAll(oldDb.lifetimeStats, oldLifetimeStatsData);
        batch.insertAll(oldDb.techniqueStats, oldTechniqueStatsData);
        batch.insertAll(oldDb.settings, oldSettingsData);
      },
      validateItems: (newDb) async {
        expect(expectedNewNotesData, await newDb.select(newDb.notes).get());
        expect(
          expectedNewPuzzleSavesData,
          await newDb.select(newDb.puzzleSaves).get(),
        );
        expect(expectedNewPacksData, await newDb.select(newDb.packs).get());
        expect(expectedNewPuzzlesData, await newDb.select(newDb.puzzles).get());
        expect(
          expectedNewSolvedPuzzlesData,
          await newDb.select(newDb.solvedPuzzles).get(),
        );
        expect(
          expectedNewLifetimeStatsData,
          await newDb.select(newDb.lifetimeStats).get(),
        );
        expect(
          expectedNewTechniqueStatsData,
          await newDb.select(newDb.techniqueStats).get(),
        );
        expect(
          expectedNewSettingsData,
          await newDb.select(newDb.settings).get(),
        );
      },
    );
  });

  // The migration that carries live player progress across `add-mistake-model`.
  // A save reaching v3 must keep its board, its notes, its elapsed time and its
  // statistics, and read as zero **mistake**s — the only honest answer, because
  // the placements that made it were never inspected.
  test(
    'migration from v2 to v3 keeps every save and adds a zero tally',
    () async {
      final stamp = DateTime.utc(2026, 9, 14, 9);
      const grid =
          '53..7....6..195....98....6.8...6...34..8.3..17...2...6.6....28....419..5....8..79';

      final oldPuzzleSavesData = <v2.PuzzleSavesData>[
        v2.PuzzleSavesData(
          puzzleId: 'p1',
          placedValues: grid,
          elapsedMs: 742000,
          isComplete: false,
          updatedAt: stamp,
          pendingUpload: true,
          deviceOrigin: 'test-device',
        ),
      ];
      final expectedNewPuzzleSavesData = <v3.PuzzleSavesData>[
        v3.PuzzleSavesData(
          puzzleId: 'p1',
          placedValues: grid,
          elapsedMs: 742000,
          isComplete: false,
          updatedAt: stamp,
          pendingUpload: true,
          deviceOrigin: 'test-device',
          mistakes: 0,
        ),
      ];

      final oldNotesData = <v2.NotesData>[
        v2.NotesData(
          puzzleId: 'p1',
          cell: 40,
          digit: 7,
          kind: 'settled',
          origin: 'generated',
          updatedAt: stamp,
          pendingUpload: true,
        ),
        v2.NotesData(
          puzzleId: 'p1',
          cell: 41,
          digit: 2,
          kind: 'provisional',
          origin: 'manual',
          updatedAt: stamp,
          pendingUpload: true,
        ),
      ];
      final expectedNewNotesData = <v3.NotesData>[
        v3.NotesData(
          puzzleId: 'p1',
          cell: 40,
          digit: 7,
          kind: 'settled',
          origin: 'generated',
          updatedAt: stamp,
          pendingUpload: true,
        ),
        v3.NotesData(
          puzzleId: 'p1',
          cell: 41,
          digit: 2,
          kind: 'provisional',
          origin: 'manual',
          updatedAt: stamp,
          pendingUpload: true,
        ),
      ];

      final oldLifetimeStatsData = <v2.LifetimeStatsData>[
        v2.LifetimeStatsData(
          id: 0,
          puzzlesSolved: 41,
          perfectSolves: 12,
          totalPlayMs: 9000000,
          updatedAt: stamp,
          pendingUpload: true,
        ),
      ];
      final expectedNewLifetimeStatsData = <v3.LifetimeStatsData>[
        v3.LifetimeStatsData(
          id: 0,
          puzzlesSolved: 41,
          perfectSolves: 12,
          totalPlayMs: 9000000,
          updatedAt: stamp,
          pendingUpload: true,
        ),
      ];

      // A player who had turned the retired auto-check on. The row survives the
      // migration untouched and is simply never read again (D-94).
      final oldSettingsData = <v2.SettingsData>[
        v2.SettingsData(
          key: 'autoCheck',
          boolValue: true,
          updatedAt: stamp,
          pendingUpload: true,
        ),
        v2.SettingsData(
          key: 'strictMode',
          boolValue: true,
          updatedAt: stamp,
          pendingUpload: true,
        ),
      ];
      final expectedNewSettingsData = <v3.SettingsData>[
        v3.SettingsData(
          key: 'autoCheck',
          boolValue: true,
          updatedAt: stamp,
          pendingUpload: true,
        ),
        v3.SettingsData(
          key: 'strictMode',
          boolValue: true,
          updatedAt: stamp,
          pendingUpload: true,
        ),
      ];

      await verifier.testWithDataIntegrity(
        oldVersion: 2,
        newVersion: 3,
        createOld: v2.DatabaseAtV2.new,
        createNew: v3.DatabaseAtV3.new,
        openTestedDatabase: AppDatabase.new,
        createItems: (batch, oldDb) {
          batch.insertAll(oldDb.notes, oldNotesData);
          batch.insertAll(oldDb.puzzleSaves, oldPuzzleSavesData);
          batch.insertAll(oldDb.lifetimeStats, oldLifetimeStatsData);
          batch.insertAll(oldDb.settings, oldSettingsData);
        },
        validateItems: (newDb) async {
          expect(
            expectedNewPuzzleSavesData,
            await newDb.select(newDb.puzzleSaves).get(),
          );
          expect(expectedNewNotesData, await newDb.select(newDb.notes).get());
          expect(
            expectedNewLifetimeStatsData,
            await newDb.select(newDb.lifetimeStats).get(),
          );
          expect(
            expectedNewSettingsData,
            await newDb.select(newDb.settings).get(),
          );
        },
      );
    },
  );
}
